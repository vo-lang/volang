import assert from 'node:assert/strict';
import {checkNativeModifiedKeys} from './kit-native-key-contracts.mjs';

export async function checkMenu(page) {
  const trigger = page.locator('#idea-menu-trigger');
  const popup = page.locator('#idea-menu');
  const item = name => popup.getByRole('menuitem', { name, exact: true });
  const focused = name => page.waitForFunction(label => document.activeElement.getAttribute('aria-label') === label, name);
  const closed = () => page.waitForFunction(() => !document.querySelector('#idea-menu').matches(':popover-open')
    && document.querySelector('#idea-menu-trigger').getAttribute('aria-expanded') === 'false');
  await trigger.focus();
  await checkNativeModifiedKeys(trigger,'ArrowDown');
  await page.keyboard.press('Enter');
  await focused('Copy idea');
  await checkNativeModifiedKeys(item('Copy idea'),'End');
  assert.equal(await popup.getAttribute('aria-labelledby'), 'idea-menu-trigger');
  await page.keyboard.press('ArrowDown');
  await focused('Create a collection');
  await page.keyboard.press('ArrowDown');
  await focused('Export collection');
  await page.keyboard.press('Enter');
  assert.equal(await trigger.getAttribute('aria-expanded'), 'true', 'disabled action dismissed the menu');
  assert.equal(await page.locator('[data-menu-result]').textContent(), 'A few useful next steps for your idea.');
  await page.keyboard.press('End');
  await focused('Rename idea');
  await page.keyboard.press('ArrowDown');
  await focused('Copy idea');
  await page.keyboard.press('End');
  await focused('Rename idea');
  await page.keyboard.press('Home');
  await focused('Copy idea');
  await page.keyboard.press('c');
  await focused('Create a collection');
  await page.keyboard.press('c');
  await focused('Copy idea');
  await page.keyboard.press('r');
  await focused('Create a collection');
  await page.keyboard.press('Enter');
  await closed();
  await page.waitForFunction(() => document.activeElement.id === 'idea-menu-trigger');
  assert.equal(await page.locator('[data-menu-result]').textContent(), 'A new collection, with room to grow.');
  await page.keyboard.press('ArrowUp');
  await focused('Rename idea');
  await page.keyboard.press('Space');
  await closed();
  await page.waitForFunction(() => document.activeElement.id === 'idea-menu-trigger');
  assert.equal(await page.locator('[data-menu-result]').textContent(), 'Every good idea deserves a good name.');
  await page.keyboard.press('Space');
  await focused('Copy idea');
  await page.keyboard.press('Tab');
  await closed();
  assert.equal(await page.evaluate(() => document.activeElement === document.querySelector('#idea-menu-trigger').closest('article').querySelector('summary')), true, 'Tab did not leave the menu for the next page control');
  await trigger.focus();
  await page.keyboard.press('ArrowDown');
  await focused('Copy idea');
  await page.keyboard.press('Shift+Tab');
  await closed();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'idea-menu-trigger', `Shift+Tab did not return to the preceding trigger: ${await page.evaluate(() => document.activeElement.outerHTML)}`);
  await trigger.click();
  await focused('Copy idea');
  await item('Rename idea').click();
  await closed();
  await page.waitForFunction(() => document.activeElement.id === 'idea-menu-trigger');
  await trigger.click();
  await focused('Copy idea');
  await page.locator('#gallery-search').click();
  await closed();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'gallery-search', 'outside dismissal stole focus');
  await trigger.focus();
  await page.keyboard.press('ArrowUp');
  await focused('Rename idea');
  await page.keyboard.press('Escape');
  await closed();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'idea-menu-trigger');
}
