const menuContracts = ['menu-native-activation', 'menu-keyboard-navigation', 'menu-disabled-actions',
  'menu-typeahead', 'menu-native-tab-exit', 'menu-pointer-and-escape'];

export async function checkStudio(browser, url, outputDirectory = resolve(root, 'target/ui-next')) {
  const reports = [];
  const defaultPage = await browser.newPage(), defaultRequests = [], defaultErrors = [];
  try {
    defaultPage.on('request', request => defaultRequests.push(request.url()));
    defaultPage.on('pageerror', error => defaultErrors.push(error.message));
    await defaultPage.goto(`${url}/studio/gallery`);
    await defaultPage.waitForFunction(() => window.__studioNext?.ready || window.__studioNext?.error);
    assert.equal(await defaultPage.evaluate(() => window.__studioNext.error), null);
    await defaultPage.getByRole('button', {name:'Make it happen'}).click();
    await defaultPage.waitForFunction(() => document.querySelector('[data-demo-count]').textContent.startsWith('1 '));
    assert(defaultRequests.some(url => url.endsWith('/artifacts/studio.vob')), 'Studio defaults to VM');
    assert(!defaultRequests.some(url => /\/artifacts\/studio\.wasm$|\/compiler\/|editor-library/.test(url)));
    assert.deepEqual(defaultErrors, []);
  } finally {await defaultPage.close();}
  for (const backend of ['vm']) {
    const context = await browser.newContext({ viewport: { width: 1400, height: 1050 } });
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(String(error)));
    page.on('request', request => requests.push(request.url()));
    await page.goto(`${url}/studio/gallery?backend=${backend}`);
    await page.waitForFunction(() => window.__studioNext?.ready || window.__studioNext?.error);
    assert.equal(await page.evaluate(() => window.__studioNext.error), null);
    await checkDialog(page);
    await checkDialogMotion(page);
    await checkDecisions(page, resolve(outputDirectory, `studio-alertdialog-${backend}.png`));
    await checkTabs(page);
    await checkForm(page);
    await checkAccordion(page);
    await checkPopover(page);
    await checkMenu(page);
    await checkCombobox(page, resolve(outputDirectory, `studio-combobox-${backend}.png`));
    await checkChoices(page);
    await checkFeedback(page, resolve(outputDirectory, `studio-feedback-${backend}.png`));
    await checkGalleryCollection(page);
    await checkTable(page, resolve(outputDirectory, `studio-table-${backend}.png`));
    await checkTooltip(page, resolve(outputDirectory, `studio-tooltip-${backend}.png`));
    await checkToasts(page, resolve(outputDirectory, `studio-toasts-${backend}.png`), backend === 'vm');
    await checkPresence(page, resolve(outputDirectory, `studio-presence-${backend}.png`));
    await page.getByRole('button', { name: 'Make it happen' }).click();
    await page.waitForFunction(() => document.querySelector('[data-demo-count]').textContent.startsWith('1 '));
    await page.locator('#gallery-name').fill('A little 中文');
    await page.locator('#studio-theme').focus();
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelector('.studio').dataset.theme === 'dark');
    assert.equal(await page.locator('#gallery-name').inputValue(), 'A little 中文');
    assert.match(await page.locator('[data-demo-count]').textContent(), /^1 /);
    await page.locator('#studio-theme').uncheck();
    await page.getByRole('link', { name: 'Documentation', exact: true }).click();
    await page.getByRole('heading', { name: 'A small idea, brought to life.' }).waitFor();
    await page.waitForFunction(() => document.activeElement.id === 'studio-content' && document.title === 'First steps · Volang Studio');
    assert.equal(new URL(page.url()).pathname, '/studio/docs');
    await page.goBack();
    await page.locator('[data-open-dialog]').click();
    await page.locator('[data-open-inner]').click();
    await page.goForward();
    await page.getByRole('heading', { name: 'A small idea, brought to life.' }).waitFor();
    await page.waitForFunction(() => !document.querySelector('dialog:modal') && document.documentElement.style.overflow === '');
    await page.getByRole('link', { name: 'State & identity', exact: true }).click();
    await page.getByRole('heading', { name: 'State that stays close.' }).waitFor();
    await page.goBack();
    await page.getByRole('heading', { name: 'A small idea, brought to life.' }).waitFor();
    await checkNestedRoutes(page);
    await checkBreadcrumb(page);
    await checkStudioScroll(page);
    assert.equal(requests.some(url => url.includes('/compiler/') || url.endsWith('/playground-ui.json')), false, 'Gallery/Docs loaded compiler or preview sources');
    await page.getByRole('link', { name: 'Playground', exact: true }).click();
    await page.locator('#playground-source').waitFor();
    const source = 'package main\nimport "fmt"\nfunc main() { fmt.Println("Hello, 中文") }\n';
    await sourceEditor(page).fill(source);
    await page.locator('[data-run]').click();
    await page.waitForFunction(() => document.querySelector('[data-output]').textContent === 'Hello, 中文\n');
    assert.equal(await page.evaluate(() => window.__studioNext.workers.started), 1);
    await sourceEditor(page).fill('package main\nfunc main() { missingName() }');
    await page.locator('[data-run]').click();
    await page.waitForFunction(() => document.querySelector('[data-output]').textContent.includes('missingName'));
    await sourceEditor(page).fill('package main\nfunc main() { for {} }');
    await page.locator('[data-run]').click();
    await page.locator('[data-stop]').click();
    await page.waitForFunction(() => document.querySelector('[data-output]').textContent.startsWith('Stopped.'));
    await sourceEditor(page).fill(source);
    await waitStudioDraft(page,source);
    await page.getByRole('link', { name: 'Gallery', exact: true }).click();
    await page.getByRole('link', { name: 'Playground', exact: true }).click();
    await page.waitForFunction(value => document.querySelector('#playground-source')?.value === value, source);
    await page.locator('[data-run]').click();
    await page.getByRole('link', { name: 'Gallery', exact: true }).click();
    await page.waitForFunction(() => window.__studioNext.workers.started === window.__studioNext.workers.stopped);
    await checkUiPlayground(page, resolve(outputDirectory, `studio-ui-playground-${backend}.png`));
    await page.screenshot({ path: resolve(outputDirectory, `studio-${backend}.png`), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile page has horizontal overflow');
    await page.screenshot({ path: resolve(outputDirectory, `studio-mobile-${backend}.png`), fullPage: true });
    await page.evaluate(async () => { window.__studioNext.close(); await window.__studioNext.done; });
    assert.equal(await page.locator('#root').textContent(), '');
    assert.deepEqual(errors, []);
    reports.push({ backend, mode: 'client', passed: true, contracts: [...dialogMotionContracts, ...menuContracts, ...choiceContracts, ...feedbackContracts, ...tableContracts, ...tooltipContracts, ...decisionContracts, ...toastContracts, ...presenceContracts, ...uiPlaygroundContracts, 'gallery-controls', 'popover-native-dismissal', 'popover-trigger-toggle', 'popover-flip-and-viewport', 'accordion-native-keyboard', 'accordion-hidden-state', 'tabs-keyboard-and-pointer', 'tabs-hidden-state', 'form-validation-and-cancellation', 'form-reset', 'native-switch-keyboard', 'theme-state-preserved', 'nested-dialogs', 'modal-tab-cycle', 'modal-escape-focus-return', 'modal-route-disposal', 'route-links', 'nested-layout-state', 'dynamic-route-identity', 'history-scroll-and-focus', 'navigation-focus-title', 'query-route', 'history-back', 'compiler-lazy', 'worker-run-unicode', 'compile-error', 'stop-worker', 'local-draft', 'route-cancellation', 'mobile-overflow', 'close'] });
    await context.close();
    console.log(`${backend}: new Studio navigation, Gallery, Docs and Playground passed`);
  }
  for (const backend of ['vm']) {
    const page = await browser.newPage();
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await page.route('**/artifacts/studio.*', async route => { await gate; await route.continue(); });
    await page.goto(`${url}/studio/docs/state?backend=${backend}&ssr`, { waitUntil: 'commit' });
    await page.getByRole('heading', { name: 'State that stays close.' }).waitFor();
    await page.evaluate(() => { window.serverHeading = document.querySelector('h1'); });
    await page.locator('#docs-search').fill('lifecycle');
    release();
    await page.waitForFunction(() => window.__studioNext?.ready || window.__studioNext?.error);
    await page.getByRole('link', { name: 'Lifecycle & requests', exact: true }).click();
    await page.getByRole('heading', { name: 'A place for every effect.' }).waitFor();
    assert.equal(await page.locator('#docs-search').inputValue(), 'lifecycle');
    assert.equal(await page.evaluate(() => window.serverHeading === document.querySelector('h1')), true);
    assert.equal(await page.evaluate(() => window.__studioNext.error), null);
    await page.screenshot({ path: resolve(outputDirectory, `studio-docs-${backend}.png`), fullPage: true });
    await page.evaluate(async () => { window.__studioNext.close(); await window.__studioNext.done; });
    reports.push({ backend, mode: 'hydrate', passed: true, contracts: ['deep-link-server-html', 'initial-data-agreement', 'server-node-adoption', 'hydrated-navigation', 'nested-route-layout-identity', 'early-layout-input-retained'] });
    await page.close();
    console.log(`${backend}: new Studio deep-link SSR adoption passed`);
  }
  for (const backend of ['vm']) {
    const page = await browser.newPage();
    let release;
    const gate = new Promise(resolve => { release = resolve; });
    await page.route('**/artifacts/studio.*', async route => { await gate; await route.continue(); });
    await page.goto(`${url}/studio/gallery?backend=${backend}&ssr`, { waitUntil: 'commit' });
    await editEarlyChoices(page);
    await page.locator('#gallery-motion-note').fill('Thought before boot 中文');
    await page.evaluate(() => { window.serverPresenceNote = document.querySelector('#gallery-motion-note'); });
    await page.locator('#gallery-table-note-outdoors').fill('Written before the page is ready 中文');
    await page.evaluate(() => { window.serverTableNote = document.querySelector('#gallery-table-note-outdoors'); });
    release();
    await page.waitForFunction(() => window.__studioNext?.ready || window.__studioNext?.error);
    assert.equal(await page.evaluate(() => window.__studioNext.error), null);
    await checkEarlyChoices(page);
    assert.equal(await page.evaluate(() => window.serverPresenceNote === document.querySelector('#gallery-motion-note')), true);
    assert.equal(await page.locator('#gallery-motion-note').inputValue(), 'Thought before boot 中文');
    assert.equal(await page.evaluate(() => window.serverTableNote === document.querySelector('#gallery-table-note-outdoors')), true);
    const pagination = page.getByRole('navigation', { name: 'Idea library pages' });
    await pagination.getByRole('button', { name: 'Page 3', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-gallery-table-page]').textContent.startsWith('Page 3'));
    await pagination.getByRole('button', { name: 'Page 1', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-gallery-table-page]').textContent.startsWith('Page 1'));
    assert.equal(await page.locator('#gallery-table-note-outdoors').inputValue(), 'Written before the page is ready 中文');
    await checkChoices(page);
    await checkFeedback(page);
    await checkGalleryCollection(page);
    await checkTable(page);
    await checkTooltip(page);
    await checkDecisions(page);
    await checkDialogMotion(page);
    await checkToasts(page);
    await checkPresence(page);
    await checkTabs(page);
    await checkForm(page);
    await checkAccordion(page);
    await checkPopover(page);
    await checkMenu(page);
    await checkCombobox(page);
    assert.equal(await page.evaluate(() => window.__studioNext.error), null);
    await page.evaluate(async () => { window.__studioNext.close(); await window.__studioNext.done; });
    reports.push({ backend, mode: 'hydrate-gallery', passed: true, contracts: [...dialogMotionContracts, ...menuContracts, ...choiceContracts, ...feedbackContracts, ...tableContracts, ...tooltipContracts, ...decisionContracts, ...toastContracts, ...presenceContracts, 'tabs-keyboard', 'tabs-hidden-state', 'tabs-native-tab-order', 'tabs-hydrated-listeners', 'accordion-hydrated-keyboard', 'accordion-hidden-state', 'popover-hydrated-interaction', 'form-validation-and-cancellation', 'form-reset'] });
    await page.close();
  }
  reports.push(...await checkUiPlaygroundSsr(browser, url));
  reports.push(...await checkStudioDocuments(browser, url, outputDirectory));
  reports.push(...await checkStudioExamplesBrowser(browser, url, outputDirectory));
  reports.push(...await checkStudioShortcuts(browser, url));
  return reports;
}
